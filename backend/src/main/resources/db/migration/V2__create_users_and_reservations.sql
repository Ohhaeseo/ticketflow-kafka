-- 사용자(테스트용 합성 계정)와 예약 테이블. PRD §9.2
CREATE TABLE users (
    id       BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nickname VARCHAR(50) NOT NULL
);

CREATE TABLE reservations (
    id              BIGINT       GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    event_id        BIGINT       NOT NULL,
    user_id         BIGINT       NOT NULL,
    idempotency_key VARCHAR(100) NOT NULL,
    request_hash    VARCHAR(64)  NOT NULL, -- 같은 키·다른 본문 판별용 SHA-256 (PRD 부록 A3)
    status          VARCHAR(20)  NOT NULL,
    failure_reason  VARCHAR(50),           -- FAILED 원인 (PRD 부록 A4)
    created_at      TIMESTAMPTZ  NOT NULL,
    updated_at      TIMESTAMPTZ  NOT NULL,

    CONSTRAINT fk_reservations_event FOREIGN KEY (event_id) REFERENCES events (id),
    CONSTRAINT fk_reservations_user  FOREIGN KEY (user_id) REFERENCES users (id),
    -- 같은 사용자의 같은 공연 예약은 1건 (FR-RSV-03)
    CONSTRAINT uk_reservations_event_user UNIQUE (event_id, user_id),
    -- 같은 사용자의 같은 멱등성 키는 1건 (FR-RSV-02)
    CONSTRAINT uk_reservations_user_idempotency_key UNIQUE (user_id, idempotency_key),
    CONSTRAINT ck_reservations_status CHECK (status IN ('QUEUED', 'CONFIRMED', 'SOLD_OUT', 'FAILED'))
);

CREATE INDEX idx_reservations_status_created_at ON reservations (status, created_at);
